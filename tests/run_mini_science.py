#!/usr/bin/env python3
"""HPC GATE 3: numerical science regression using original Graf implementation.

Run in the SAME scientific environment as real HPC data (netCDF4, pycomlink,
numba). Generates artificial 2-day data. Does NOT touch the seven real files.
The expected result is generated by a separate test implementation calling the
UNCHANGED original graf()/estimate()/meta2() directly, not the new wrapper.
Both directions of two links are compared; also test ID shuffles and deliberate
corruption. Synthetic PASS does not imply identity to the true 2020--21 output.
"""
from pathlib import Path
import argparse
import json
import sys
import shutil
import numpy as np
import xarray as xr
ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT/'src'))
sys.path.insert(0,str(ROOT/'tests'))
from mini_fixture import create,sha
from essd_cz.compare import compare
from essd_cz import rain5


def run(root):
    root=Path(root).resolve()
    if root.exists() and any(root.iterdir()):
        raise FileExistsError(f'Clean fixture directory required; refusing overwrite: {root}')
    root.mkdir(parents=True,exist_ok=True)
    base=root/'baseline'
    paths=create(base,scientific_reference=True)
    before={r:sha(p) for r,p in paths.items()}
    print('GATE 3a: exact matching source functions versus 5-min values derived from the native 1-min fixture',flush=True)
    baseline=compare(paths,root/'compare_baseline',link_indices=[0,2],days=2,
                     atol=1e-4,rtol=1e-4,numba_threads=2,make_plot=True)
    if not baseline['all_pass']:
        raise AssertionError('Synthetic original-vs-wrapper NUMERICAL mismatch. See compare_baseline/comparison_report.json')
    print('PASS: both sublinks, links 0 and 2',flush=True)
    print('GATE 3a-extra: missing direction must be preserved, never crash or be invented',flush=True)
    from essd_cz.rainfall import aggregate_exact, producer
    with xr.open_dataset(paths['qc']) as qc, xr.open_dataset(paths['rain'],mask_and_scale=False) as native:
        sparse=aggregate_exact(producer(),qc,1,numba_threads=2)
        published=rain5.derive_link_5min(native,1)
        assert sparse['estimate_errors'], 'Expected one recorded all-missing directional failure'
        np.testing.assert_array_equal(sparse['graf_wet_5min'][:,1],published['graf_wet_5min'].isel(sublink_id=1,cml_id=0).values)
        np.testing.assert_array_equal(np.isnan(sparse['R_sublink_5min'][:,1]),
            np.isnan(published['R_sublink_5min'].isel(sublink_id=1,cml_id=0).values))
        assert np.isnan(sparse['R_sublink_5min'][:,1]).all()
        assert np.isfinite(sparse['R_sublink_5min'][:,0]).any()
    print('PASS: one all-missing direction reported, other direction retained',flush=True)
    rpath=Path(paths['rain'])

    def publish_variant(label,transform):
        variant=root/label;variant.mkdir()
        target=variant/rpath.name
        with xr.open_dataset(rpath,mask_and_scale=False) as ds:
            d=ds.load()
        transformed=transform(d)
        transformed.to_netcdf(target,engine='netcdf4')
        modified=dict(paths);modified['rain']=str(target)
        return modified

    print('GATE 3b: reversed CML and directional order must still match by ID',flush=True)
    shuffled=publish_variant('shuffled',lambda ds:ds.isel(cml_id=[2,0,1],sublink_id=[1,0]))
    check_shuffle=compare(shuffled,root/'compare_shuffle',link_indices=[0,2],days=2,
                         numba_threads=2,make_plot=False)
    if not check_shuffle['all_pass']:
        raise AssertionError('Structural ID/sublink order mapping was broken')
    print('PASS: shuffled indices',flush=True)

    def corrupt_numeric(ds):
        arr=ds['R_sublink_1min'].values
        pos=np.flatnonzero(np.isfinite(arr[:,0,0])&(ds['graf_valid_1min'].values[:,0,0]==1))
        if not len(pos):raise AssertionError('No finite synthetic values for negative control')
        arr[pos[len(pos)//2],0,0]+=4.0
        return ds
    print('GATE 3c: deliberate rainfall corruption must NOT pass',flush=True)
    corrupted=publish_variant('corrupted_rate',corrupt_numeric)
    check_corrupt=compare(corrupted,root/'compare_corruption',link_indices=[0],days=2,
                          numba_threads=2,make_plot=False)
    if check_corrupt['all_pass']:
        raise AssertionError('CORRUPTION WAS NOT DETECTED')
    print('PASS: corruption detected',flush=True)

    def corrupt_flag(ds):
        a=ds['graf_wet_1min'].values
        # flip a wet minute inside a complete valid 5-minute block so the
        # derived wet-minute count (and possibly the wet flag) must change
        valid=(ds['graf_valid_1min'].values[:,0,0]==1)
        complete=np.repeat(valid.reshape(-1,5).all(axis=1),5)
        cand=np.flatnonzero(complete&(a[:,0,0]==1))
        if not len(cand):raise AssertionError('No wet minute in a complete block for negative control')
        a[int(cand[len(cand)//2]),0,0]=np.uint8(0)
        return ds
    print('GATE 3d: changed wet/dry flag must NOT pass',flush=True)
    badflag=publish_variant('corrupted_flags',corrupt_flag)
    check_flag=compare(badflag,root/'compare_flags',link_indices=[0],days=2,
                       numba_threads=2,make_plot=False)
    if check_flag['all_pass']:
        raise AssertionError('FLAG CORRUPTION WAS NOT DETECTED')
    print('PASS: flag corruption detected',flush=True)

    after={r:sha(p) for r,p in paths.items()}
    if after!=before:
        raise AssertionError('One of the original synthetic inputs changed: data integrity compromised')
    print('PASS: synthetic originals unchanged byte-for-byte',flush=True)
    report={'gate':'HPC MINI-SCIENCE / artificial two-day data only',
            'status':'PASS',
            'full_original_rainfall_reproduction':'NOT TESTED',
            'tested_links':[0,2],
            'checks':['numerical rates and masks','thresholds','five-minute flags and counts',
                      'CML ID and directional order independence','corruption rejected',
                      'wet flag mutation rejected','all-missing direction preserved without aborting link',
                      'source file hashes unchanged'],
            'fixture_sha256':before,
            'baseline_comparison':str(root/'compare_baseline/comparison_report.json')}
    (root/'MINI_SCIENCE_RESULTS.json').write_text(json.dumps(report,indent=2)+'\n')
    print('ALL SYNTHETIC HPC TESTS PASSED:',root,flush=True)
    return 0

if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument('--out-dir',type=Path,default=ROOT/'results/mini_hpc_test')
    a=p.parse_args()
    sys.exit(run(a.out_dir))
